"""Slot form descriptor generated from the read-only booking JSON Schema.

The descriptor is deliberately conservative: unsupported schema keywords or
types fail closed instead of being silently dropped. The same descriptor drives
both the Python validators and the static browser form generated by
``ui.build``.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from dataclasses import dataclass
from datetime import date
from typing import Any

from .errors import UiValidationError

EMAIL_FORMAT_PATTERN = re.compile(r"[^@\s]+@[^@\s]+\.[^@\s]+")
DATE_FORMAT_PATTERN = re.compile(r"\d{4}-\d{2}-\d{2}")
SUPPORTED_SCALARS = frozenset({"string", "integer", "number", "boolean"})
SUPPORTED_SCALAR_KEYS = frozenset(
    {"type", "description", "enum", "format", "minimum", "maximum", "minLength", "maxLength"}
)
SUPPORTED_OBJECT_KEYS = frozenset(
    {"type", "properties", "required", "additionalProperties", "description"}
)


@dataclass(frozen=True)
class FormField:
    """One flattened, schema-derived slot input."""

    path: str
    json_type: str
    required: bool
    description: str = ""
    enum: tuple[str, ...] = ()
    format: str | None = None
    minimum: float | None = None
    maximum: float | None = None
    min_length: int | None = None
    max_length: int | None = None

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable descriptor for this field."""
        return {
            "path": self.path,
            "json_type": self.json_type,
            "required": self.required,
            "description": self.description,
            "enum": list(self.enum),
            "format": self.format,
            "minimum": self.minimum,
            "maximum": self.maximum,
            "min_length": self.min_length,
            "max_length": self.max_length,
        }


@dataclass(frozen=True)
class FormDescriptor:
    """Generated form contract with its source schema hash."""

    schema_sha256: str
    schema_version: str
    allow_unknown_fields: bool
    fields: tuple[FormField, ...]
    cross_field_rules: tuple[str, ...]

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable descriptor consumed by the static UI."""
        return {
            "schema_sha256": self.schema_sha256,
            "schema_version": self.schema_version,
            "allow_unknown_fields": self.allow_unknown_fields,
            "fields": [field.to_dict() for field in self.fields],
            "cross_field_rules": list(self.cross_field_rules),
        }


@dataclass(frozen=True)
class ValidationIssue:
    """One deterministic validator failure."""

    path: str
    code: str

    def to_dict(self) -> dict[str, str]:
        """Return a JSON-serialisable issue; no rejected value is included."""
        return {"field": self.path, "code": self.code}


def _scalar_field(path: str, spec: Mapping[str, Any], required: bool) -> FormField:
    """Build one scalar field, rejecting any constraint this harness cannot enforce."""
    unsupported = set(spec) - SUPPORTED_SCALAR_KEYS
    if unsupported:
        raise UiValidationError(f"unsupported schema keywords for {path}: {sorted(unsupported)}")
    json_type = str(spec["type"])
    if json_type not in SUPPORTED_SCALARS:
        raise UiValidationError(f"unsupported schema type for {path}: {json_type}")
    fmt = spec.get("format")
    if fmt is not None and json_type == "string" and fmt not in {"date", "email"}:
        raise UiValidationError(f"unsupported string format for {path}: {fmt}")
    if fmt is not None and json_type != "string":
        raise UiValidationError(f"format is only supported for strings: {path}")
    raw_enum = spec.get("enum", ())
    if not isinstance(raw_enum, (list, tuple)) or not all(isinstance(v, str) for v in raw_enum):
        raise UiValidationError(f"enum must be a list of strings for {path}")
    return FormField(
        path=path,
        json_type=json_type,
        required=required,
        description=str(spec.get("description", "")),
        enum=tuple(str(value) for value in raw_enum),
        format=str(fmt) if fmt is not None else None,
        minimum=_number_constraint(spec, "minimum", path),
        maximum=_number_constraint(spec, "maximum", path),
        min_length=_int_constraint(spec, "minLength", path),
        max_length=_int_constraint(spec, "maxLength", path),
    )


def _number_constraint(spec: Mapping[str, Any], key: str, path: str) -> float | None:
    """Return a numeric constraint, failing closed on a non-numeric value."""
    value = spec.get(key)
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise UiValidationError(f"{key} must be numeric for {path}")
    return float(value)


def _int_constraint(spec: Mapping[str, Any], key: str, path: str) -> int | None:
    """Return an integer constraint, failing closed on a non-integer value."""
    value = spec.get(key)
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int):
        raise UiValidationError(f"{key} must be an integer for {path}")
    return value


def _fields_from_properties(
    properties: Mapping[str, Any], required: list[str], prefix: str = ""
) -> tuple[FormField, ...]:
    """Flatten schema properties into deterministic dotted-path fields."""
    fields: list[FormField] = []
    for name in sorted(properties):
        spec = properties[name]
        if not isinstance(spec, Mapping):
            raise UiValidationError(f"property spec must be an object: {name}")
        path = f"{prefix}.{name}" if prefix else str(name)
        json_type = spec.get("type")
        if json_type == "object":
            unsupported = set(spec) - SUPPORTED_OBJECT_KEYS
            if unsupported:
                raise UiValidationError(
                    f"unsupported object keywords for {path}: {sorted(unsupported)}"
                )
            if spec.get("additionalProperties") is not False:
                raise UiValidationError(f"nested object must forbid extra properties: {path}")
            nested = spec.get("properties")
            if not isinstance(nested, Mapping):
                raise UiValidationError(f"nested object needs properties: {path}")
            nested_required = spec.get("required", [])
            if not isinstance(nested_required, list) or not all(
                isinstance(item, str) for item in nested_required
            ):
                raise UiValidationError(f"nested required must be a string list: {path}")
            fields.extend(_fields_from_properties(nested, nested_required, path))
            continue
        fields.append(_scalar_field(path, spec, path in required))
    return tuple(fields)


def build_form_descriptor(schema: Mapping[str, Any], schema_sha256: str) -> FormDescriptor:
    """Generate a conservative form descriptor from a booking JSON Schema.

    Args:
        schema: Parsed ``schemas/booking.schema.json`` (read-only).
        schema_sha256: Digest of the exact schema bytes consumed.

    Returns:
        A descriptor with flattened fields and documented cross-field rules.

    Raises:
        UiValidationError: If the schema uses an unsupported shape or keyword.

    """
    if schema.get("type") != "object":
        raise UiValidationError("booking schema root must be an object")
    properties = schema.get("properties")
    if not isinstance(properties, Mapping):
        raise UiValidationError("booking schema root needs properties")
    required = schema.get("required", [])
    if not isinstance(required, list) or not all(isinstance(item, str) for item in required):
        raise UiValidationError("booking schema required must be a string list")
    allow_unknown = schema.get("additionalProperties", False) is not False
    fields = _fields_from_properties(properties, required)
    paths = {field.path for field in fields}
    rules: list[str] = []
    if "check_in" in paths and "check_out" in paths:
        rules.append("check_out_after_check_in")
    return FormDescriptor(
        schema_sha256=schema_sha256,
        schema_version=str(schema.get("schema_version", "unknown")),
        allow_unknown_fields=allow_unknown,
        fields=fields,
        cross_field_rules=tuple(rules),
    )


def _flatten_values(
    descriptor: FormDescriptor, values: Mapping[str, Any]
) -> tuple[dict[str, Any], list[ValidationIssue]]:
    """Flatten nested slot values using the descriptor's dotted paths."""
    prefixes = {field.path.rsplit(".", 1)[0] for field in descriptor.fields if "." in field.path}
    flat: dict[str, Any] = {}
    issues: list[ValidationIssue] = []
    field_paths = {field.path for field in descriptor.fields}
    for key, value in values.items():
        if not isinstance(key, str):
            issues.append(ValidationIssue(str(key), "unexpected_key_type"))
            continue
        if key in prefixes:
            if not isinstance(value, Mapping):
                issues.append(ValidationIssue(key, "expected_object"))
                continue
            for sub_key, sub_value in value.items():
                child = f"{key}.{sub_key}"
                if child not in field_paths:
                    issues.append(ValidationIssue(child, "unknown_field"))
                    continue
                flat[child] = sub_value
            continue
        if key not in field_paths:
            issues.append(ValidationIssue(key, "unknown_field"))
            continue
        flat[key] = value
    return flat, issues


def _validate_one(field: FormField, value: Any, issues: list[ValidationIssue]) -> None:
    """Validate one flattened value against its generated field descriptor."""
    if field.json_type == "integer":
        if isinstance(value, bool) or not isinstance(value, int):
            issues.append(ValidationIssue(field.path, "expected_integer"))
            return
    elif field.json_type == "number":
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            issues.append(ValidationIssue(field.path, "expected_number"))
            return
    elif field.json_type == "boolean":
        if not isinstance(value, bool):
            issues.append(ValidationIssue(field.path, "expected_boolean"))
            return
    elif not isinstance(value, str):
        issues.append(ValidationIssue(field.path, "expected_string"))
        return
    if field.enum and value not in field.enum:
        issues.append(ValidationIssue(field.path, "not_in_enum"))
    if (
        field.minimum is not None
        and isinstance(value, (int, float))
        and not isinstance(value, bool)
    ):
        if value < field.minimum:
            issues.append(ValidationIssue(field.path, "below_minimum"))
    if (
        field.maximum is not None
        and isinstance(value, (int, float))
        and not isinstance(value, bool)
    ):
        if value > field.maximum:
            issues.append(ValidationIssue(field.path, "above_maximum"))
    if isinstance(value, str):
        if field.min_length is not None and len(value) < field.min_length:
            issues.append(ValidationIssue(field.path, "too_short"))
        if field.max_length is not None and len(value) > field.max_length:
            issues.append(ValidationIssue(field.path, "too_long"))
        if field.format == "date":
            if DATE_FORMAT_PATTERN.fullmatch(value) is None:
                issues.append(ValidationIssue(field.path, "invalid_date"))
            else:
                try:
                    date.fromisoformat(value)
                except ValueError:
                    issues.append(ValidationIssue(field.path, "invalid_date"))
        if field.format == "email" and EMAIL_FORMAT_PATTERN.fullmatch(value) is None:
            issues.append(ValidationIssue(field.path, "invalid_email"))


def validate_slots(
    descriptor: FormDescriptor, values: Mapping[str, Any]
) -> tuple[ValidationIssue, ...]:
    """Validate slot values against the generated descriptor and cross-field rules.

    Args:
        descriptor: Descriptor produced by :func:`build_form_descriptor`.
        values: Candidate booking slots, optionally nested under ``contact``.

    Returns:
        Issues sorted by ``(field, code)``; an empty tuple means valid.

    """
    flat, issues = _flatten_values(descriptor, values)
    for field in descriptor.fields:
        if field.required and field.path not in flat:
            issues.append(ValidationIssue(field.path, "required"))
        elif field.path in flat:
            _validate_one(field, flat[field.path], issues)
    if "check_out_after_check_in" in descriptor.cross_field_rules:
        start = flat.get("check_in")
        end = flat.get("check_out")
        if (
            isinstance(start, str)
            and isinstance(end, str)
            and DATE_FORMAT_PATTERN.fullmatch(start)
            and DATE_FORMAT_PATTERN.fullmatch(end)
        ):
            try:
                if date.fromisoformat(end) <= date.fromisoformat(start):
                    issues.append(ValidationIssue("check_out", "check_out_after_check_in"))
            except ValueError:
                pass
    return tuple(sorted(set(issues), key=lambda issue: (issue.path, issue.code)))
